def theme_ids() -> list[str]:
    """全部主题 id(保持定义顺序)。"""
    return list(THEMES.keys())


def build_pool(cfg: dict) -> list[str]:
    """合并自定义文案与勾选的主题文案,得到本次可用的完整文案池。"""
    pool = [str(t) for t in (cfg.get("messages") or []) if str(t).strip()]
    for tid in cfg.get("themes") or []:
        pool.extend(THEMES.get(str(tid), []))
    return pool


def render(template: str) -> str:
    """渲染单条模板,替换内置变量。"""
    msg = str(template).strip()
    now = datetime.now()
    msg = msg.replace("[日期]", now.strftime("%m月%d日")).replace("[date]", now.strftime("%m月%d日"))
    msg = msg.replace("[时间]", now.strftime("%H:%M")).replace("[time]", now.strftime("%H:%M"))
    return msg


def pick(pool: list[str], last_sent: str = "") -> str:
    """从文案池选一条,尽量避开上次发送的内容。"""
    candidates = [render(t) for t in pool if render(t)]
    if not candidates:
        return "🔥 续火花"
    fresh = [c for c in candidates if c != last_sent]
    return random.choice(fresh) if fresh else random.choice(candidates)
